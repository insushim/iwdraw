/** 스탬프의 카테고리(def.cat 우선, 없으면 기존 매핑). */
function catOf(s: StampDef): StampCategory | undefined {
  return s.cat ?? LEGACY_CAT[s.id];
}

/** 팔레트용 — 카테고리별로 묶어 표시 순서대로 반환(분류 없는 스탬프는 "기타"로 맨 뒤). */
export function groupedStamps(): { cat: string; stamps: StampDef[] }[] {
  const groups: { cat: string; stamps: StampDef[] }[] = STAMP_CATEGORIES.map((cat) => ({
    cat,
    stamps: STAMPS.filter((s) => catOf(s) === cat),
  }));
  const rest = STAMPS.filter((s) => {
    const c = catOf(s);
    return !c || !STAMP_CATEGORIES.includes(c);
  });
  if (rest.length) groups.push({ cat: "기타", stamps: rest });
  return groups.filter((g) => g.stamps.length > 0);
}

/**
 * 스탬프를 캔버스에 그린다(뚝딱그림 수락·무비 재생 공용).
 * evenodd 채우기 = 웃는 얼굴 눈처럼 안쪽 서브패스가 구멍으로 뚫린다.
 * fill 없는 path는 잉크(브러시 색)로 채우고, 윤곽은 항상 잉크 선.
 */
export function drawStampOnCtx(
  ctx: CanvasRenderingContext2D,
  def: StampDef,
  cx: number,
  cy: number,
  sizePx: number,
  ink: { r: number; g: number; b: number },
): void {
  const s = sizePx / 24; // 뷰박스 24 기준
  ctx.save();
  ctx.globalCompositeOperation = "source-over"; // 호출부의 지우개/블렌드 상태 오염 방지
  ctx.translate(cx - sizePx / 2, cy - sizePx / 2);
  ctx.scale(s, s);
  // 뚝딱그림은 "선화(도안)"만 남긴다 — 색은 아이가 칠한다(2026-07-13 사용자 지시).
  // 채우기를 하면 스탬프가 이미 완성된 그림이 되어 색칠할 여지가 없다.
  ctx.lineWidth = 1.3;
  ctx.lineJoin = "round";
  ctx.lineCap = "round";
  ctx.strokeStyle = `rgb(${ink.r},${ink.g},${ink.b})`; // 선 색은 사용자가 고른 색
  ctx.globalAlpha = 1;
  for (const p of def.paths) {
    ctx.stroke(new Path2D(p.d));
  }
  ctx.restore();
}
